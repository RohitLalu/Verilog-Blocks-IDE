import{topPorts}from'./graphToVerilog.js';

// A starting cocotb test for the design: random values on every input, outputs logged, and a place for the checks.
// Works with cocotb 1.8+ and 2.x (Timer's unit is passed positionally; values are read with int()).
export function generateCocotbTest(nodes,edges,style='basic'){
  if(style==='pyuvm')return generatePyuvmTest(nodes,edges);
  const{topIn,topOut}=topPorts(nodes,edges);
  const rnd=p=>p.width>1?`random.randint(0, ${2**p.width-1})`:'random.randint(0, 1)';
  const show=ps=>ps.map(p=>`${p.sig}={int(dut.${p.sig}.value)}`).join(' ');
  return[
    '# cocotb test for the design "top", written by VerilogBlocks IDE. Edit it freely, then press Run.',
    '# Docs: https://docs.cocotb.org',
    'import random',
    '',
    'import cocotb',
    'from cocotb.triggers import Timer',
    '',
    '',
    '@cocotb.test()',
    'async def random_inputs(dut):',
    '    """Apply random values to every input and log what the outputs do."""',
    '    random.seed(1)  # the same values every run',
    '    for step in range(16):',
    ...(topIn.length?topIn.map(p=>`        dut.${p.sig}.value = ${rnd(p)}`):['        pass  # the design has no inputs']),
    '        await Timer(10, "ns")',
    `        dut._log.info(f"step {step}: ${show(topIn)} -> ${show(topOut)}")`,
    '        # Check the outputs here, for example:',
    ...(topOut.length?[`        # assert int(dut.${topOut[0].sig}.value) == expected, "explain what went wrong"`]:[]),
    '',
  ].join('\n');
}

// The same idea with UVM's structure in Python (pyuvm on cocotb): a sequence of random items goes through a sequencer to a
// driver, which applies them and sends what it saw to a scoreboard. Put the reference model in Scoreboard.write().
function generatePyuvmTest(nodes,edges){
  const{topIn,topOut}=topPorts(nodes,edges);
  const max=p=>2**p.width-1;
  const ins=topIn.map(p=>p.sig),outs=topOut.map(p=>p.sig);
  return[
    '# UVM-style test with pyuvm (UVM in Python, on cocotb), written by VerilogBlocks IDE. Edit it freely, then press Run.',
    '# Docs: https://pyuvm.github.io/pyuvm',
    'import random',
    '',
    'import cocotb',
    'import pyuvm',
    'from cocotb.triggers import Timer',
    'from pyuvm import uvm_analysis_port, uvm_driver, uvm_env, uvm_sequence, uvm_sequence_item, uvm_sequencer, uvm_subscriber, uvm_test',
    '',
    '',
    'class Item(uvm_sequence_item):',
    '    """One set of input values."""',
    '    def __init__(self, name="item"):',
    '        super().__init__(name)',
    ...(ins.length?ins.map(n=>`        self.${n} = 0`):['        pass']),
    '',
    '    def randomize(self):',
    ...(topIn.length?topIn.map(p=>`        self.${p.sig} = random.randint(0, ${max(p)})`):['        pass']),
    '',
    '    def __str__(self):',
    '        return f"'+ins.map(n=>`${n}={self.${n}}`).join(' ')+'"',
    '',
    '',
    'class RandomSequence(uvm_sequence):',
    '    async def body(self):',
    '        for _ in range(16):',
    '            item = Item()',
    '            await self.start_item(item)',
    '            item.randomize()',
    '            await self.finish_item(item)',
    '',
    '',
    'class Driver(uvm_driver):',
    '    """Applies each item to the design and reports what the outputs did (driver and monitor in one, to keep it short)."""',
    '    def build_phase(self):',
    '        self.ap = uvm_analysis_port("ap", self)',
    '',
    '    def start_of_simulation_phase(self):',
    '        self.dut = cocotb.top',
    '',
    '    async def run_phase(self):',
    '        while True:',
    '            item = await self.seq_item_port.get_next_item()',
    ...ins.map(n=>`            self.dut.${n}.value = item.${n}`),
    '            await Timer(10, "ns")',
    `            self.ap.write((item, {${outs.map(n=>`"${n}": int(self.dut.${n}.value)`).join(', ')}}))`,
    '            self.seq_item_port.item_done()',
    '',
    '',
    'class Scoreboard(uvm_subscriber):',
    '    """Checks every result. Put your reference model here and compare."""',
    '    def build_phase(self):',
    '        self.seen = 0',
    '',
    '    def write(self, txn):',
    '        item, outputs = txn',
    '        self.seen += 1',
    '        self.logger.info(f"{item} -> {outputs}")',
    ...(outs.length?[`        # expected = ...                       # from item.${ins[0]||'...'}, ...`,`        # assert outputs["${outs[0]}"] == expected, f"{item}: got {outputs}"`]:[]),
    '',
    '    def check_phase(self):',
    '        assert self.seen > 0, "the scoreboard saw no results"',
    '',
    '',
    'class Env(uvm_env):',
    '    def build_phase(self):',
    '        self.sequencer = uvm_sequencer("sequencer", self)',
    '        self.driver = Driver("driver", self)',
    '        self.scoreboard = Scoreboard("scoreboard", self)',
    '',
    '    def connect_phase(self):',
    '        self.driver.seq_item_port.connect(self.sequencer.seq_item_export)',
    '        self.driver.ap.connect(self.scoreboard.analysis_export)',
    '',
    '',
    '@pyuvm.test()',
    'class RandomTest(uvm_test):',
    '    def build_phase(self):',
    '        self.env = Env("env", self)',
    '',
    '    async def run_phase(self):',
    '        self.raise_objection()',
    '        await RandomSequence("sequence").start(self.env.sequencer)',
    '        self.drop_objection()',
    '',
  ].join('\n');
}
